"use client";

import { useEffect } from "react";
import { useRouter, Link } from "@/i18n/navigation";
import { useAuth } from "@/contexts/AuthContext";

export default function DashboardPage() {
  const { user, isLoading } = useAuth();
  const router = useRouter();

  useEffect(() => {
    if (!isLoading && !user) router.replace("/login");
  }, [isLoading, user, router]);

  if (isLoading || !user) return null;

  return (
    <div className="max-w-5xl mx-auto px-4 sm:px-6 py-10">
      <div className="mb-8">
        <h1 className="text-2xl font-bold text-slate-800">Collection Dashboard</h1>
        <p className="text-slate-500 mt-1">Welcome back, {user.first_name ?? user.username}.</p>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
        <DashCard href="/objects" title="Objects" description="Browse and manage your collection records" icon={ObjectsIcon} />
        <DashCard href="/locations" title="Locations" description="Manage storage locations and movements" icon={LocationIcon} />
        <DashCard href="/entries" title="Object Entries" description="Record incoming objects before acquisition" icon={EntryIcon} />
        <DashCard href="/acquisitions" title="Acquisitions" description="Formal ownership and accession records" icon={AcquisitionIcon} />
        <DashCard href="/parties" title="Parties" description="People and organisations in your collection" icon={PartyIcon} />
        <DashCard href="/browse" title="Public Portal" description="View what's published to the public" icon={BrowseIcon} />
      </div>
    </div>
  );
}

